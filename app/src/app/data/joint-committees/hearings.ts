// Every hearing the joint committees have held in the 194th General Court, and
// the few they canceled.
//
// Taken on 15 October 2026 from the legislature's API:
//
//   /api/GeneralCourts/194/Committees/{code}, for which hearings each committee
//   lists.
//
//   /api/Hearings/{id}, for each hearing's date, description and status.
//
// The API lists 44 more hearings that it then will not return ("not supported
// in this API"). The committee's Hearings tab on malegislature.gov does not show
// them either, so they are left out. The 379 here are the tab's list, hearing
// for hearing, for all thirty-four committees.
//
// The date agrees with the hearing's own page for all 379. The Hearings tab
// differs in two ways: for a hearing that was moved it shows the date it was
// moved from, and for some written testimony hearings it shows the day
// testimony closed rather than the day it opened.
//
// The status is the API's. The hearing's own page says "Rescheduled" for any
// hearing that was ever moved, whatever came of it, while the API says whether
// it was then held or canceled. Racial Equity's two January 2026 hearings are
// the case in point: both were moved, the API has both canceled, and a hearing
// on the second one's subject was held on 31 March.
//
// No hearing listed is still to come. The last was on 6 October 2026.
//
// Bundled rather than fetched, as the committees are: the API sends no CORS
// headers.

export interface JointHearing {
  /** The legislature's event id, which is also the hearing's page. */
  id: number;
  /** Boston time, as the hearing's own page gives it. */
  date: string;
  /**
   * The hearing's description as the legislature wrote it, line breaks run
   * together. Sometimes a subject, sometimes the whole announcement.
   */
  topic: string;
  status: "Completed" | "Canceled";
}

